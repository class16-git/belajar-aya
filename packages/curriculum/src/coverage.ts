import { FRAMEWORKS, STAGES, type Framework, type Stage } from '@atlas/shared';
import type { Catalog } from './catalog';
import { isVisible, publicationIssues, requiresReligiousReview } from './publication';
import type { Lesson, Objective } from './schema';

/**
 * Coverage of the age-2 → Grade-6 objective registry by actual lessons.
 * - planned: no lesson yet
 * - draft: only draft lessons
 * - awaiting_religious_review: lessons exist but the religious gate is not met
 * - awaiting_review: agent-checked lessons waiting for human content review
 * - published: at least one lesson visible in production (human-reviewed)
 */
export const COVERAGE_STATUSES = ['planned', 'draft', 'awaiting_religious_review', 'awaiting_review', 'published'] as const;
export type CoverageStatus = (typeof COVERAGE_STATUSES)[number];

export interface ObjectiveCoverage {
  objective: Objective;
  lessons: Lesson[];
  status: CoverageStatus;
}

export function lessonsForObjective(catalog: Catalog, o: Objective): Lesson[] {
  return catalog.lessons.filter((l) => o.implementation.skillIds.includes(l.skillId) || l.objectiveIds.includes(o.id));
}

export function objectiveStatus(lessons: Lesson[]): CoverageStatus {
  if (lessons.length === 0) return 'planned';
  if (lessons.some((l) => isVisible(l, 'reviewed'))) return 'published';
  if (lessons.some((l) => requiresReligiousReview(l))) return 'awaiting_religious_review';
  if (lessons.some((l) => l.reviewStatus === 'agent_reviewed')) return 'awaiting_review';
  return 'draft';
}

export function coverage(catalog: Catalog): ObjectiveCoverage[] {
  return catalog.objectives.map((objective) => {
    const lessons = lessonsForObjective(catalog, objective);
    return { objective, lessons, status: objectiveStatus(lessons) };
  });
}

export type CoverageCell = Record<CoverageStatus, number> & { total: number };
export type CoverageMatrix = Record<Stage, Record<Framework, CoverageCell>>;

const emptyCell = (): CoverageCell => ({ planned: 0, draft: 0, awaiting_religious_review: 0, awaiting_review: 0, published: 0, total: 0 });

export function coverageMatrix(rows: ObjectiveCoverage[]): CoverageMatrix {
  const m = Object.fromEntries(STAGES.map((s) => [s, Object.fromEntries(FRAMEWORKS.map((f) => [f, emptyCell()]))])) as CoverageMatrix;
  for (const r of rows) {
    const cell = m[r.objective.stage][r.objective.framework];
    cell[r.status] += 1;
    cell.total += 1;
  }
  return m;
}

export interface ReviewQueueItem {
  lesson: Lesson;
  /** Who must act: content reviewer, religious reviewer, or the author (draft). */
  needs: ('author' | 'content_review' | 'religious_review')[];
  reasons: string[];
}

/** Every lesson not yet visible in production, with what blocks it. Drafts included (parent-only view). */
export function reviewQueue(catalog: Catalog): ReviewQueueItem[] {
  return catalog.lessons
    .filter((l) => !isVisible(l, 'reviewed'))
    .map((lesson) => {
      const needs: ReviewQueueItem['needs'] = [];
      if (lesson.reviewStatus === 'draft') needs.push('author');
      if (requiresReligiousReview(lesson) && lesson.religiousReview?.approvalStatus !== 'approved') needs.push('religious_review');
      if (lesson.reviewStatus === 'draft' || lesson.reviewStatus === 'agent_reviewed') needs.push('content_review');
      return { lesson, needs, reasons: publicationIssues(lesson).map((i) => i.message) };
    });
}

/** Markdown report (committed at docs/curriculum/COVERAGE_REPORT.md and kept current by CI). */
export function coverageReportMarkdown(catalog: Catalog): string {
  const rows = coverage(catalog);
  const m = coverageMatrix(rows);
  const fwLabel: Record<Framework, string> = {
    montessori: 'Montessori',
    singapore_math: 'Maths (CPA)',
    robotics_stem: 'Robotics/STEM',
    islamic_studies: 'Islamic studies',
  };
  const stageLabel: Record<Stage, string> = {
    age2_3: 'Age 2–3', age3_4: 'Age 3–4', age4_5: 'Age 4–5', k: 'Kindergarten',
    g1: 'Grade 1', g2: 'Grade 2', g3: 'Grade 3', g4: 'Grade 4', g5: 'Grade 5', g6: 'Grade 6',
  };
  const cell = (c: CoverageCell) => (c.total === 0 ? '—' : `${c.published}/${c.total}` + (c.total - c.published - c.planned > 0 ? ` (+${c.total - c.published - c.planned} unpublished)` : ''));
  const count = (s: CoverageStatus) => rows.filter((r) => r.status === s).length;
  const lines: string[] = [];
  lines.push('# Curriculum coverage report', '');
  lines.push('> Generated by `pnpm curriculum:coverage` from `content/`. Do not edit by hand; CI fails if it is stale.', '');
  lines.push(`Curriculum version ${catalog.curriculumVersion} · ${rows.length} objectives · ${catalog.lessons.length} lessons`, '');
  lines.push('| Status | Objectives |', '|---|---:|');
  for (const s of COVERAGE_STATUSES) lines.push(`| ${s.replace(/_/g, ' ')} | ${count(s)} |`);
  lines.push('', '## Published / total objectives by stage and framework', '');
  lines.push(`| Stage | ${FRAMEWORKS.map((f) => fwLabel[f]).join(' | ')} |`);
  lines.push(`|---|${FRAMEWORKS.map(() => '---').join('|')}|`);
  for (const s of STAGES) lines.push(`| ${stageLabel[s]} | ${FRAMEWORKS.map((f) => cell(m[s][f])).join(' | ')} |`);
  lines.push('', '## Objectives by stage', '');
  for (const s of STAGES) {
    lines.push(`### ${stageLabel[s]}`, '');
    lines.push('| Objective | Framework / strand | Status | Lessons | Review flags |', '|---|---|---|---|---|');
    for (const r of rows.filter((x) => x.objective.stage === s)) {
      const o = r.objective;
      lines.push(`| \`${o.id}\` ${o.title.en} | ${fwLabel[o.framework]} / ${o.strand} | ${r.status.replace(/_/g, ' ')} | ${r.lessons.map((l) => l.id).join(', ') || '—'} | ${o.reviewFlags.join(', ') || '—'} |`);
    }
    lines.push('');
  }
  const queue = reviewQueue(catalog);
  lines.push('## Human review queue', '');
  if (queue.length === 0) lines.push('Nothing waiting.', '');
  else {
    lines.push('| Lesson | Status | Needs | Reasons |', '|---|---|---|---|');
    for (const q of queue) lines.push(`| \`${q.lesson.id}\` | ${q.lesson.reviewStatus} | ${q.needs.join(', ')} | ${q.reasons.join('; ') || '—'} |`);
    lines.push('');
  }
  return lines.join('\n');
}
