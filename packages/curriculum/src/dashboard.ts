import { STAGES, type Stage } from '@atlas/shared';
import type { Catalog } from './catalog';
import { isBookVisible, isPassageVisible, libraryMinStatus, type Library } from './library';
import { isVisible } from './publication';

/** Expansion targets (owner mandate): 150 curriculum units and 150 reading materials per level. */
export const TARGET_PER_LEVEL = { units: 150, readings: 150 } as const;

const BAND_STAGE: Record<string, Stage> = { toddler: 'age2_3', preschool: 'age3_4', prek: 'age4_5', kindergarten: 'k', g1: 'g1', g2: 'g2', g3: 'g3', g4: 'g4', g5: 'g5', g6: 'g6' };
const LABEL: Record<Stage, string> = { age2_3: 'Age 2–3', age3_4: 'Age 3–4', age4_5: 'Age 4–5', k: 'Kindergarten', g1: 'Grade 1', g2: 'Grade 2', g3: 'Grade 3', g4: 'Grade 4', g5: 'Grade 5', g6: 'Grade 6' };

/**
 * Actual content counts per level, by pipeline state, against the targets. Counts come from the content files;
 * "live" uses the same gates as production (`reviewed`). Nothing here is estimated.
 */
export function contentDashboard(cat: Catalog, lib: Library) {
  const stageOfObjective = new Map(cat.objectives.map((o) => [o.id, o.stage]));
  return STAGES.map((stage) => {
    // A unit counts for the stages of its objectives; units written before the objective registry fall back to
    // their age band.
    const lessons = cat.lessons.filter((l) => (l.objectiveIds.length ? l.objectiveIds.some((id) => stageOfObjective.get(id) === stage) : BAND_STAGE[l.ageBand] === stage));
    const passages = lib.passages.filter((p) => p.stage === stage);
    const books = lib.books.filter((b) => b.stages.includes(stage));
    return {
      stage,
      label: LABEL[stage],
      unitIds: lessons.map((l) => l.id),
      liveUnitIds: lessons.filter((l) => isVisible(l, 'reviewed')).map((l) => l.id),
      units: {
        live: lessons.filter((l) => isVisible(l, 'reviewed')).length,
        awaitingHuman: lessons.filter((l) => l.reviewStatus === 'agent_reviewed').length,
        draft: lessons.filter((l) => l.reviewStatus === 'draft').length,
        total: lessons.length,
      },
      readings: {
        live: passages.filter((p) => isPassageVisible(p, 'reviewed')).length + books.filter((b) => isBookVisible(b, lib.sources, libraryMinStatus('reviewed'))).length,
        awaitingHuman: passages.filter((p) => !isPassageVisible(p, 'reviewed')).length + books.filter((b) => !isBookVisible(b, lib.sources, libraryMinStatus('reviewed'))).length,
        total: passages.length + books.length,
        originalPassages: passages.length,
        externalBooks: books.length,
      },
    };
  });
}

export function contentDashboardMarkdown(cat: Catalog, lib: Library): string {
  const rows = contentDashboard(cat, lib);
  const pct = (n: number, t: number) => `${Math.round((100 * n) / t)}%`;
  const sum = (f: (r: (typeof rows)[number]) => number) => rows.reduce((a, r) => a + f(r), 0);
  const T = TARGET_PER_LEVEL;
  const lines = [
    '# Content dashboard (actual counts)',
    '',
    '<!-- Generated by `pnpm content:dashboard`. CI fails if this file is stale. Do not edit by hand. -->',
    '',
    `Targets: **${T.units} curriculum units** and **${T.readings} reading materials** per level (${T.units * STAGES.length} + ${T.readings * STAGES.length} in total).`,
    'The **Live** columns use the production gate: a human review is recorded and there are no unresolved safety, factual or rights issues.',
    'The **Awaiting human** columns count content that passed the agent checks but is not live. A unit may serve several levels.',
    '',
    '| Level | Units live | Units awaiting human | Units draft | Units vs target | Readings live | Readings awaiting human | Readings (passages + books) vs target |',
    '|---|---|---|---|---|---|---|---|',
    ...rows.map((r) => `| ${r.label} | ${r.units.live} | ${r.units.awaitingHuman} | ${r.units.draft} | ${r.units.live}/${T.units} (${pct(r.units.live, T.units)}) | ${r.readings.live} | ${r.readings.awaitingHuman} | ${r.readings.live}/${T.readings} (${pct(r.readings.live, T.readings)}) · ${r.readings.originalPassages} passages, ${r.readings.externalBooks} books |`),
    `| **All levels (unique units: ${cat.lessons.length})** | ${sum((r) => r.units.live)} | ${sum((r) => r.units.awaitingHuman)} | ${sum((r) => r.units.draft)} | ${pct(sum((r) => r.units.live), T.units * STAGES.length)} | ${sum((r) => r.readings.live)} | ${sum((r) => r.readings.awaitingHuman)} | ${pct(sum((r) => r.readings.live), T.readings * STAGES.length)} |`,
    '',
  ];
  return lines.join('\n');
}

// ── Expansion (new units and readings) ───────────────────────────────────────────────────────────────────────────────
import type { ExpansionSummary } from './expansion-store';
import { PIPELINE_STATES, UNIT_FRAMEWORKS, READING_GENRES, type PipelineState } from './units';

export const EXPANSION_TARGET_PER_LEVEL = { units: 150, readings: 150 } as const;
type StateCounts = Record<PipelineState, number> & { total: number };
const empty = (): StateCounts => ({ drafted: 0, structurally_validated: 0, subject_validated: 0, human_reviewed: 0, published: 0, rejected: 0, total: 0 });

/** Actual counts of NEW expansion content by level, subject and pipeline state (machine-readable). */
export function expansionDashboard(exp: ExpansionSummary) {
  const byLevel = Object.fromEntries(STAGES.map((s) => [s, { units: empty(), readings: empty() }])) as Record<Stage, { units: StateCounts; readings: StateCounts }>;
  const byFramework = Object.fromEntries(UNIT_FRAMEWORKS.map((f) => [f, empty()])) as Record<string, StateCounts>;
  const byGenre = Object.fromEntries(READING_GENRES.map((g) => [g, empty()])) as Record<string, StateCounts>;
  const bump = (c: StateCounts, st: PipelineState) => { c[st]++; c.total++; };
  for (const x of exp.items) {
    if (x.kind === 'unit') {
      bump(byLevel[x.level].units, x.state);
      bump(byFramework[x.framework!]!, x.state);
    } else {
      bump(byLevel[x.level].readings, x.state);
      bump(byGenre[x.genre!]!, x.state);
    }
  }
  const totals = { units: empty(), readings: empty() };
  for (const s of STAGES) for (const k of ['units', 'readings'] as const) for (const st of [...PIPELINE_STATES, 'rejected', 'total'] as const) totals[k][st] += byLevel[s][k][st];
  const islamic = exp.items.filter((x) => x.religious).length;
  return {
    targets: { perLevel: EXPANSION_TARGET_PER_LEVEL, units: EXPANSION_TARGET_PER_LEVEL.units * STAGES.length, readings: EXPANSION_TARGET_PER_LEVEL.readings * STAGES.length },
    totals,
    byLevel,
    byFramework,
    byGenre,
    awaitingScholar: islamic,
    validationErrors: exp.errors.length,
  };
}

export function expansionDashboardMarkdown(exp: ExpansionSummary): string {
  const d = expansionDashboard(exp);
  const cell = (c: StateCounts) => `${c.total} (✓ ${c.subject_validated + c.human_reviewed + c.published} · 👤 ${c.human_reviewed + c.published} · ● ${c.published}${c.rejected ? ` · ✗ ${c.rejected}` : ''})`;
  return [
    '',
    '## Expansion content (new units and readings, 2026-11 mandate)',
    '',
    `Targets: ${d.targets.units} new units and ${d.targets.readings} new readings (${d.targets.perLevel.units} + ${d.targets.perLevel.readings} per level).`,
    'Each cell shows the total authored, then: ✓ passed structural and subject validation · 👤 human-reviewed · ● published (live) · ✗ rejected.',
    'A draft that has not passed validation counts only in the total.',
    `Validation errors in the corpus: **${d.validationErrors}**. Islamic items waiting for a qualified scholar: **${d.awaitingScholar}**.`,
    '',
    '| Level | Units | Units vs target | Readings | Readings vs target |',
    '|---|---|---|---|---|',
    ...STAGES.map((s) => `| ${LABEL[s]} | ${cell(d.byLevel[s].units)} | ${d.byLevel[s].units.total}/${d.targets.perLevel.units} | ${cell(d.byLevel[s].readings)} | ${d.byLevel[s].readings.total}/${d.targets.perLevel.readings} |`),
    `| **Total** | ${cell(d.totals.units)} | ${d.totals.units.total}/${d.targets.units} | ${cell(d.totals.readings)} | ${d.totals.readings.total}/${d.targets.readings} |`,
    '',
    '| Units by framework | Count |',
    '|---|---|',
    ...Object.entries(d.byFramework).map(([f, c]) => `| ${f} | ${cell(c)} |`),
    '',
    '| Readings by genre | Count |',
    '|---|---|',
    ...Object.entries(d.byGenre).filter(([, c]) => c.total > 0).map(([g, c]) => `| ${g} | ${cell(c)} |`),
    '',
    'Machine-readable: [`content-dashboard.json`](content-dashboard.json).',
    '',
  ].join('\n');
}
