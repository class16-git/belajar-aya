/** Regenerates src/content-index.ts from content/**: lessons, skills.json and objectives/*.json. */
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = join(import.meta.dirname, '../../../content');
const lessons = [];
const objectives = [];
const walk = (dir) => {
  for (const f of readdirSync(dir).sort()) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (/^lesson-.*\.json$/.test(f)) lessons.push(relative(root, p));
    else if (relative(root, dir) === 'objectives' && f.endsWith('.json')) objectives.push(relative(root, p));
  }
};
walk(root);
lessons.sort();
objectives.sort();
const lines = ['// Generated by `pnpm --filter @atlas/curriculum index` — do not edit by hand.', ''];
lessons.forEach((f, i) => lines.push(`import l${i} from '../../../content/${f}';`));
objectives.forEach((f, i) => lines.push(`import o${i} from '../../../content/${f}';`));
lines.push("import skills from '../../../content/skills.json';", '');
lines.push(`export const RAW_LESSONS: unknown[] = [${lessons.map((_, i) => `l${i}`).join(', ')}];`);
lines.push(`export const RAW_LESSON_FILES: string[] = ${JSON.stringify(lessons)};`);
lines.push(`export const RAW_OBJECTIVES: unknown[] = [${objectives.map((_, i) => `o${i}`).join(', ')}];`);
lines.push(`export const RAW_OBJECTIVE_FILES: string[] = ${JSON.stringify(objectives)};`);
lines.push('export const RAW_SKILLS: unknown = skills;', '');
writeFileSync(join(import.meta.dirname, '../src/content-index.ts'), lines.join('\n'));
console.log(`Indexed ${lessons.length} lessons and ${objectives.length} objective files.`);
